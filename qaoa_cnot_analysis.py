import re
import math
import sympy as sp
import symengine as se


def simplify_binary_expression(expr):
    """
    Simplify only powers of binary variables in SymEngine expressions
    Preserve exponents after parentheses
    """
    # Convert SymEngine expression to string
    expr_str = str(expr)

    # Pattern matching only variable exponents (exclude exponents after parentheses)
    pattern = r'([a-zA-Z][a-zA-Z0-9_]*)\*\*[1-9][0-9]*'

    # Replace matched parts with variable name only (remove exponent)
    simplified_str = re.sub(pattern, r'\1', expr_str)

    # Convert string back to SymEngine expression
    result = se.sympify(simplified_str)
    return result


def count_cnots_from_terms(terms_list, n_layers=1):
    """
    Compute the number of CNOTs directly from terms_list (no quantum device needed)

    Parameters:
    -----------
    terms_list : list
        List generated by process_polynomial_simple()
    n_layers : int
        Number of QAOA layers

    Returns:
    --------
    int : Total CNOT count
    """
    cnot_per_layer = 0
    # Count terms with 2 or more bodies
    for n in range(2, len(terms_list)):
        if isinstance(terms_list[n], dict):
            for indices, coeff in terms_list[n].items():
                # CNOTs required per n-body term: 2 * (n - 1)
                # forward ladder: (n-1) CNOTs
                # backward ladder: (n-1) CNOTs
                cnot_per_layer += 2 * (len(indices) - 1)

    return cnot_per_layer * n_layers


def process_polynomial_simple(polynomial, n_vars):
    """Process polynomial and build terms_list"""
    import sympy as sp
    S = polynomial
    poly = sp.Poly(S) if not isinstance(S, sp.Poly) else S

    terms = []
    for monom, coeff in poly.terms():
        terms.append((float(coeff), monom))

    max_body = n_vars
    terms_list = [0] + [{} for _ in range(max_body)]
    for coeff, bits in terms:
        vars_involved = [i for i, bit in enumerate(bits) if bit == 1]
        num_vars = len(vars_involved)

        if num_vars == 0:
            terms_list[0] += coeff
        elif num_vars == 1:
            terms_list[num_vars][vars_involved[0]] = coeff
        elif num_vars <= max_body:
            terms_list[num_vars][tuple(vars_involved)] = coeff

    return terms_list


